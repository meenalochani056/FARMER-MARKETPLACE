import { Router } from 'express';
import { body } from 'express-validator';
import { createOrder, getOrder, listOrders, updateOrderStatus } from '../controllers/orderController.js';
import { authenticate, allowRoles } from '../middleware/auth.js';
import validate from '../middleware/validate.js';
const router = Router();
router.use(authenticate);
router.post('/', allowRoles('buyer'), [body('items').isArray({ min: 1 }), body('deliveryAddress').isObject()], validate, createOrder);
router.get('/', listOrders);
router.get('/:id', getOrder);
router.put('/:id/status', allowRoles('farmer', 'admin'), body('status').isIn(['CONFIRMED', 'PROCESSING', 'READY_FOR_PICKUP', 'PICKED_UP', 'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED', 'REJECTED']), validate, updateOrderStatus);
export default router;
