import { Router } from 'express';
import { body } from 'express-validator';
import { adminList, adminStats, adminUsers, createCategory, deleteCategory, updateCategory, verifyFarmer } from '../controllers/miscController.js';
import { authenticate, allowRoles } from '../middleware/auth.js';
import validate from '../middleware/validate.js';
const router = Router();
router.use(authenticate, allowRoles('admin'));
router.get('/stats', adminStats);
router.get('/farmers', adminUsers);
router.get('/buyers', adminUsers);
router.get('/resources/:resource', adminList);
router.put('/farmers/:id/verify', body('status').isIn(['verified', 'rejected']), validate, verifyFarmer);
router.post('/categories', createCategory);
router.put('/categories/:id', updateCategory);
router.delete('/categories/:id', deleteCategory);
router.get('/:resource', adminList);
export default router;
